// Regenerates src/core/generator/effWordlist.ts from scripts/eff_large_wordlist.txt.
import fs from 'node:fs';
const words = fs.readFileSync(new URL('./eff_large_wordlist.txt', import.meta.url), 'utf8')
  .trim().split('\n').map((l) => l.split('\t')[1].trim());
if (words.length !== 7776 || new Set(words).size !== 7776) throw new Error('Unexpected wordlist shape');
fs.writeFileSync(new URL('../src/core/generator/effWordlist.ts', import.meta.url),
  '// EFF Large Wordlist for passphrases (7776 words).\n' +
  '// Source: https://www.eff.org/dice — licensed under CC BY 3.0 US (see NOTICE.md).\n' +
  '// Generated by scripts/build-wordlist.mjs — do not edit by hand.\n' +
  `export const EFF_WORDLIST: readonly string[] = ${JSON.stringify(words.join(' '))}.split(' ');\n`);
